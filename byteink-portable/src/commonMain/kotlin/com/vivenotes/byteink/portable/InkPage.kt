package com.vivenotes.byteink.portable

import com.vivenotes.byteink.kit.*

/** A borrowed projection owned by its InkPage; copying the data value does not copy its engine handle. */
public data class InkProjection(
    public val id: String,
    public val stroke: InkStroke,
    public val transform: InkTransform = InkTransform(),
    public val brushVersion: Int = InkBrushCatalog.BRUSH_VERSION,
    public val colorFollowsTheme: Boolean? = null,
    public val groupId: String? = null,
) {
    public val pageBounds: InkBounds? get() = stroke.bounds?.let(transform::apply)
}

/** Owns decoded/derived geometry. Stored records survive close and are never regenerated by replay. */
public class InkPage internal constructor(
    public val strokes: List<InkProjection>,
    public val sourceStrokes: List<InkProjection>,
    public val erasedAway: List<String>,
    public val unreadable: List<String>,
    public val ignoredOperations: List<String>,
    public val storedStrokes: List<StoredInkStroke>,
    public val storedErases: List<StoredInkErase>,
    public val storedMoves: List<StoredInkMove>,
    private val owned: Set<InkStroke>,
) : AutoCloseable {
    private var closed = false
    override public fun close() { if (!closed) { closed = true; owned.forEach(InkStroke::close) } }
}

private sealed class Operation(public val id: String, public val createdAt: Long) {
    class Erase(val row: StoredInkErase) : Operation(row.id, row.createdAt)
    class Move(val row: StoredInkMove) : Operation(row.id, row.createdAt)
}

internal fun loadInkPage(kit: InkKit, pageId: String, strokes: List<StoredInkStroke>, erases: List<StoredInkErase>,
                         moves: List<StoredInkMove>): InkPage {
    val savedStrokes = strokes.map { it.copy(points = it.points.copyOf()) }
    val savedErases = erases.map { it.copy(points = it.points.copyOf(), targetIds = it.targetIds.toList()) }
    val savedMoves = moves.map { it.copy(points = it.points.copyOf(), targetIds = it.targetIds.toList()) }
    val owned = linkedSetOf<InkStroke>()
    fun own(stroke: InkStroke): InkStroke = stroke.also { owned += it }
    try {
        val unreadable = mutableListOf<String>()
        val source = savedStrokes.filter { it.pageId == pageId && it.deletedAt == null }
            .sortedWith(compareBy<StoredInkStroke> { it.seq }.then { a, b -> compareCodePoints(a.id, b.id) })
            .mapNotNull { row -> kit.decode(row)?.let { InkProjection(row.id, own(it), brushVersion = row.brushVersion,
                colorFollowsTheme = row.colorFollowsTheme, groupId = row.groupId) } ?: run { unreadable += row.id; null } }
        class Bucket(val order: Int, var projections: List<InkProjection>)
        val buckets = source.mapIndexed { index, projection -> Bucket(index, listOf(projection)) }
        val byId = mutableMapOf<String, MutableList<Bucket>>()
        buckets.forEach { byId.getOrPut(it.projections.single().id) { mutableListOf() }.add(it) }
        val sourceHandles = source.map { it.stroke }.toSet()
        fun retire(stroke: InkStroke) { if (stroke !in sourceHandles && owned.remove(stroke)) stroke.close() }
        val ignored = mutableListOf<String>()
        val operations = buildList {
            savedErases.filter { it.deletedAt == null }.forEach { add(Operation.Erase(it)) }
            savedMoves.filter { it.deletedAt == null }.forEach { add(Operation.Move(it)) }
        }.sortedWith(compareBy(Operation::createdAt, Operation::id))
        for (operation in operations) when (operation) {
            is Operation.Erase -> {
                val row = operation.row
                val mode = InkEraseMode.of(row.mode)
                val mask = if (row.pageId == pageId && mode != null) kit.decodeErase(row)?.let(::own) else null
                if (mask == null) { ignored += row.id; continue }
                if (mask.bounds != null) for (id in row.targetIds.toSet()) for (bucket in byId[id].orEmpty()) {
                    val before = bucket.projections
                    bucket.projections = buildList {
                        for (projection in before) {
                            val outlinesOnly = projection.stroke.style.familyId == InkBrushCatalog.HIGHLIGHTER
                            if (mode == InkEraseMode.Normal) {
                                val cut = own(projection.stroke.subtract(mask, projection.transform))
                                if (outlinesOnly) {
                                    if (cut.bounds != null) add(projection.copy(stroke = cut)) else retire(cut)
                                } else {
                                    for (piece in cut.split(projection.transform)) {
                                        own(piece)
                                        if (piece.bounds != null) add(projection.copy(stroke = piece)) else retire(piece)
                                    }
                                    retire(cut)
                                }
                            } else if (outlinesOnly) {
                                if (!projection.stroke.intersects(mask, projection.transform)) add(projection)
                            } else for (piece in projection.stroke.split(projection.transform)) {
                                own(piece)
                                if (piece.bounds != null && !piece.intersects(mask, projection.transform)) add(projection.copy(stroke = piece))
                                else retire(piece)
                            }
                        }
                    }
                    val kept = bucket.projections.map { it.stroke }.toSet()
                    before.filter { it.stroke !in kept }.forEach { retire(it.stroke) }
                }
                retire(mask)
            }
            is Operation.Move -> {
                val row = operation.row
                val path = if (row.pageId == pageId) kit.decodeMove(row) else null
                if (path == null || !row.dxDp.isFinite() || !row.dyDp.isFinite() || !row.scaleX.isFinite() ||
                    !row.scaleY.isFinite() || row.scaleX <= 0 || row.scaleY <= 0 || !row.anchorX.isFinite() || !row.anchorY.isFinite()) {
                    ignored += row.id; continue
                }
                val targets = row.targetIds.toSet().flatMap { byId[it].orEmpty() }.filter { it.projections.isNotEmpty() }.sortedBy { it.order }
                if (targets.isEmpty()) continue
                val projected = readOrNull {
                    moveProjections(targets.flatMap { it.projections }, row, path).also { result ->
                        require(result.all { projection -> projection.pageBounds?.let {
                            it.left.isFinite() && it.top.isFinite() && it.right.isFinite() && it.bottom.isFinite()
                        } ?: true }) { "Move/resize overflows page coordinates" }
                    }
                }
                if (projected == null) { ignored += row.id; continue }
                var offset = 0
                for (bucket in targets) {
                    val size = bucket.projections.size
                    bucket.projections = projected.subList(offset, offset + size).toList()
                    offset += size
                }
            }
        }
        val current = buckets.flatMap { it.projections }
        val drawn = current.map { it.id }.toSet()
        return InkPage(current.toList(), source.toList(), source.mapNotNull { it.id.takeIf { id -> id !in drawn } }.distinct(),
            unreadable.toList(), ignored.toList(), savedStrokes, savedErases, savedMoves, owned.toSet())
    } catch (failure: Throwable) { owned.forEach(InkStroke::close); throw failure }
}

private fun moveProjections(current: List<InkProjection>, row: StoredInkMove, path: List<InkPoint>): List<InkProjection> {
    val selected = current.map { it.stroke.enclosedBy(path, it.transform) }
    val bounds = current.filterIndexed { i, _ -> selected[i] }.mapNotNull { it.pageBounds }.unionBounds()
    val delta = bounds?.let { PageBounds.clampTranslation(it, row.dxDp, row.dyDp) } ?: InkPoint(row.dxDp, row.dyDp)
    val moved = current.mapIndexed { i, projection -> if (selected[i]) projection.copy(transform = projection.transform.copy(
        offsetX = projection.transform.offsetX + delta.x, offsetY = projection.transform.offsetY + delta.y)) else projection }
    if (row.scaleX == 1f && row.scaleY == 1f) return moved
    // Match Android: select again after translation, then clamp the whole resize once.
    val resized = moved.map { it.stroke.enclosedBy(path, it.transform) }
    val resizeBounds = moved.filterIndexed { i, _ -> resized[i] }.mapNotNull { it.pageBounds }.unionBounds()
    val anchor = InkPoint(row.anchorX, row.anchorY)
    val scale = resizeBounds?.let { PageBounds.clampScale(it, anchor, row.scaleX, row.scaleY) }
        ?: InkPoint(row.scaleX, row.scaleY)
    return moved.mapIndexed { i, projection -> if (resized[i]) {
        val old = projection.transform
        projection.copy(transform = InkTransform(old.scaleX * scale.x, old.scaleY * scale.y,
            anchor.x + (old.offsetX - anchor.x) * scale.x, anchor.y + (old.offsetY - anchor.y) * scale.y))
    } else projection }
}

private fun compareCodePoints(a: String, b: String): Int {
    fun point(value: String, at: Int): Int {
        val first = value[at].code
        return if (first in 0xd800..0xdbff && at + 1 < value.length && value[at + 1].code in 0xdc00..0xdfff)
            0x10000 + ((first - 0xd800) shl 10) + value[at + 1].code - 0xdc00 else first
    }
    var i = 0; var j = 0
    while (i < a.length && j < b.length) {
        val x = point(a, i); val y = point(b, j)
        if (x != y) return x.compareTo(y)
        i += if (x > 0xffff) 2 else 1; j += if (y > 0xffff) 2 else 1
    }
    return (a.length - i).compareTo(b.length - j)
}
